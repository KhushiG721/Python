"""
Demonstrates Python assignment operators.
"""

# --------------------------------------------------
# 1. Basic Assignment
# --------------------------------------------------

score = 100

print("Initial Score:", score)


# --------------------------------------------------
# 2. Addition Assignment
# --------------------------------------------------

score += 20

print("\nAfter += 20:", score)


# --------------------------------------------------
# 3. Subtraction Assignment
# --------------------------------------------------

score -= 10

print("After -= 10:", score)


# --------------------------------------------------
# 4. Multiplication Assignment
# --------------------------------------------------

score *= 2

print("After *= 2:", score)


# --------------------------------------------------
# 5. Division Assignment
# --------------------------------------------------

score /= 2

print("After /= 2:", score)


# --------------------------------------------------
# 6. Floor Division Assignment
# --------------------------------------------------

points = 17

points //= 3

print("\nAfter //= 3:", points)


# --------------------------------------------------
# 7. Modulus Assignment
# --------------------------------------------------

points = 17

points %= 5

print("After %= 5:", points)


# --------------------------------------------------
# 8. Exponentiation Assignment
# --------------------------------------------------

number = 2

number **= 3

print("After **= 3:", number)